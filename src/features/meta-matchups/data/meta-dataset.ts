const build = (
  pokemonId: string,
  league: League,
  fastMoveId: string,
  chargedMove1Id: string,
  chargedMove2Id: string,
): BattleBuild => ({
  pokemonId,
  league,
  attackIv: 0,
  defenseIv: 15,
  staminaIv: 15,
  level: league === "master" ? 50 : 20,
  fastMoveId,
  chargedMove1Id,
  chargedMove2Id,
  shields: 1,
});
const entry = (
  id: string,
  name: string,
  formId: string,
  league: League,
  weight: number,
  configuredBuild: BattleBuild,
  category?: string,
): MetaEntry => ({
  id,
  speciesId: configuredBuild.pokemonId,
  formId,
  name,
  league,
  build: configuredBuild,
  weight,
  sourceVersion: "arena-meta-fixture-v1",
  ...(category ? { category } : {}),
});

